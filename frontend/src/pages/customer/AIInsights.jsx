import { useEffect, useRef, useState } from 'react';
import { aiApi } from '../../api/client.js';
import { Alert } from '../../components/ui.jsx';
import { formatDateTime } from '../../utils/format.js';

const SUGGESTIONS = [
  'Summarize my last five orders.',
  'Which of my orders are still not delivered?',
  'How much did I spend this week?',
  'Which food items have I ordered most frequently?',
];

export default function AIInsights() {
  const [question, setQuestion] = useState('');
  const [history, setHistory] = useState([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const endRef = useRef(null);

  useEffect(() => {
    endRef.current?.scrollIntoView({ behavior: 'smooth', block: 'end' });
  }, [history, loading]);

  const ask = async (q) => {
    const text = (q ?? question).trim();
    if (text.length < 3 || loading) return;
    setError('');
    setLoading(true);
    setQuestion('');
    try {
      const res = await aiApi.ask(text);
      setHistory((h) => [...h, { question: text, ...res }]);
    } catch (err) {
      setError(err.status === 429 ? `⏳ ${err.message}` : err.message);
      setQuestion(text);
    } finally {
      setLoading(false);
    }
  };

  const onSubmit = (e) => {
    e.preventDefault();
    ask();
  };

  return (
    <section className="insights">
      <div className="page-head">
        <div>
          <h1>✨ AI order insights</h1>
          <p className="muted">Ask anything about your own CampusBite order history. Only your orders are shared with the AI.</p>
        </div>
      </div>

      <div className="chip-row">
        {SUGGESTIONS.map((s) => (
          <button key={s} type="button" className="chip" onClick={() => ask(s)} disabled={loading}>
            {s}
          </button>
        ))}
      </div>

      <div className="chat card">
        {history.length === 0 && !loading && (
          <p className="muted center">Pick a suggestion above or type your own question below.</p>
        )}
        {history.map((h, idx) => (
          <div key={idx} className="chat-turn">
            <div className="bubble user">{h.question}</div>
            <div className="bubble ai">
              <div className="ai-text">{h.answer}</div>
              <div className="ai-meta muted small">
                {h.source === 'openai' ? `Generated by ${h.model}` : 'Basic summary (OpenAI key not configured on the server)'} ·{' '}
                {h.orders_considered} orders analysed · {formatDateTime(h.generated_at)}
              </div>
            </div>
          </div>
        ))}
        {loading && (
          <div className="bubble ai typing" aria-live="polite">
            Thinking<span className="dots">…</span>
          </div>
        )}
        <div ref={endRef} />
      </div>

      <Alert onClose={() => setError('')}>{error}</Alert>

      <form className="ask-form" onSubmit={onSubmit}>
        <input
          value={question}
          onChange={(e) => setQuestion(e.target.value)}
          placeholder="e.g. What did I order from Spice Route last week?"
          maxLength={500}
          aria-label="Your question"
        />
        <button className="btn btn-primary" disabled={loading || question.trim().length < 3}>
          {loading ? 'Asking…' : 'Ask'}
        </button>
      </form>
    </section>
  );
}
